/** Icons drawn bold somewhere (a 2.25+ stroke at a call site). */
const BOLD = new Set(["check", "layers"]);

/** A React element tree -> [tag, props] pairs (Fragments flattened). */
function nodes(el) {
  if (el == null || el === false) return [];
  if (Array.isArray(el)) return el.flatMap(nodes);
  const { children, ...props } = el.props ?? {};
  if (typeof el.type === "symbol" || el.type?.toString?.().includes("Fragment")) return nodes(children);
  return [[el.type, props], ...nodes(children)];
}

const out = {};
for (const [name, component] of Object.entries(ICONS)) {
  // By file path: the package's exports map doesn't expose the per-weight definitions.
  const mod = await import(new URL(`../node_modules/@phosphor-icons/react/dist/defs/${component}.mjs`, import.meta.url).href);
  const weights = mod.default;
  const pick = ["regular", "fill", ...(BOLD.has(name) ? ["bold"] : [])];
  out[name] = Object.fromEntries(
    pick.map((w) => {
      const els = nodes(weights.get(w));
      // Phosphor draws every icon we use with plain paths; anything else would need the renderer to grow.
      if (els.some(([tag, attrs]) => tag !== "path" || Object.keys(attrs).some((k) => k !== "d"))) throw new Error(`${component} ${w}: not plain paths`);
      return [w, els.map(([, attrs]) => attrs.d)];
    }),
  );
}

const body = `/* Generated by scripts/build-icons.mjs from @phosphor-icons/react (MIT). Do not edit by hand. */
/** Each weight is the icon's SVG path data on Phosphor's 256 x 256 grid. */
export interface IconWeights {
  regular: string[];
  fill: string[];
  bold?: string[];
}

export const ICON_PATHS = ${JSON.stringify(out)} satisfies Record<string, IconWeights>;
`;
writeFileSync(fileURLToPath(new URL("../components/ui/iconPaths.ts", import.meta.url)), body);
